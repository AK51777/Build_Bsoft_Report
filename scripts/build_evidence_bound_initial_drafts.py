    def is_standard(item: dict[str, Any]) -> bool:
        policy_type = str(item.get("policy_type") or "").casefold()
        return policy_type in {"evaluation_rule", "standard", "technical_standard", "specification"} or bool(
            re.search(r"标准|规范|评价|测评|指南", item.get("title", ""))
        )

    basis_entries = [
        item for item in policy_material.get("basis_entries", [])
        if is_standard(item) == standard_mode
    ]
    catalog_candidates = [
        item for item in policy_material.get("catalog_candidates", [])
        if (item.get("basis_group") == "standard") == standard_mode
    ]
    selected_ids = {item["policy_id"] for item in basis_entries}
    paragraphs = [
        item for item in policy_material.get("background_paragraphs", [])
        if item["policy_id"] in selected_ids
    ]

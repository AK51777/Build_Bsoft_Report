            ["客户范围", "建设领域", "建设方式", "范围状态", "验收目标"],
            [
                [
                    scope["standard_name"],
                    scope_domain(scope),
                    MODE_LABELS.get(scope.get("construction_mode"), "待确认"),
                    SCOPE_STATUS_LABELS.get(scope.get("status"), "待确认"),
                    scope.get("acceptance_target") or "深化设计阶段确认",
                ]
                for scope in chapter_scopes
            ],

def compact(value: str) -> str:
    return re.sub(r"\s+", "", value or "")


def safe_title(value: str) -> str:
    return re.sub(r"[<>:\"/\\|?*]+", "_", value).strip(" .")


def json_list(value: str | list[Any] | None) -> list[Any]:
    if isinstance(value, list):
        return value
    return json.loads(value or "[]")


def truncate_sentence(text: str, limit: int) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= limit:
        return text
    candidate = text[:limit]
    boundary = max(candidate.rfind(mark) for mark in "。；，")
    return candidate[:boundary + 1] if boundary >= limit // 2 else candidate.rstrip("，； ") + "。"


def sanitize_standard_text(text: str, forbidden_terms: list[str], title: str) -> str:
    value = text.replace("\r", "\n")
    for term in [*forbidden_terms, "BsoftGPT", "Bsoft", "创业慧康", "创业的产品资源"]:
        if term:
            value = value.replace(term, "")
    replacements = {
        "本院": "医院",
        "我院": "医院",
        "国家卫生部": "国家卫生健康主管部门",
        "卫生部": "卫生健康主管部门",
        "已经实现": "拟实现",
        "已实现": "拟实现",
        "实现了": "拟实现",
        "达到了": "拟达到",
    }
    for source, target in replacements.items():
        value = value.replace(source, target)
    fragments = []
    for raw in re.split(r"(?<=[。；;])|[\n]+", value):
        item = raw.strip(" -—；;，,")
        if not item or compact(item) == compact(title):
            continue
        if item.count("/") >= 2 and any(term in item for term in ("清单", "可选", "必选", "详见")):
            continue
        if re.search(
            r"(?:达到|提升|降低|缩短|不少于|不超过|入径率|完成率)[^。；]{0,36}"
            r"\d+(?:\.\d+)?\s*(?:%|级|天|月|年|万元|亿元|个|套|项)",
            item,
        ):
            continue
        if re.search(r"\d{2,}(?:\s*\+\s*\d+)?\s*(?:个|项|套|种|例)", item):
            continue
        if sum(term in item for term in ("缩短", "降低", "提高", "提升", "减少", "满意度")) >= 2:
            continue
        if any(term in item for term in ("DVD", "市场占有率", "客户遍布", "标杆产品")):
            continue
        if any(term in item for term in ("国内领先", "国内第一", "市场制高点", "抢占市场")):
            continue
        item = item.replace(",", "，").replace(";", "；")
        if item[-1:] not in "。；！？":
            item += "。"
        fragments.append(item)
    return truncate_sentence("".join(fragments[:5]), 420)


def sanitize_confirmed_standard_text(
    text: str,
    forbidden_terms: list[str],
    title: str,
) -> str:
    """Preserve every approved sentence for a confirmed capability assembly.

    Confirmed standard blocks have already passed corpus review.  At this stage we
    may normalise project voice and remove explicitly forbidden vendor terms, but
    must not rank, summarise, drop, or truncate their approved content.
    """
    value = text.replace("\r\n", "\n").replace("\r", "\n")
    for term in [*forbidden_terms, "BsoftGPT", "Bsoft", "创业慧康", "创业的产品资源"]:
        if term:
            value = value.replace(term, "")
    replacements = {
        "本院": "医院",
        "我院": "医院",
        "国家卫生部": "国家卫生健康主管部门",
        "卫生部": "卫生健康主管部门",
        "已经实现": "拟实现",
        "已实现": "拟实现",
        "实现了": "拟实现",
        "达到了": "拟达到",
    }
    for source, target in replacements.items():
        value = value.replace(source, target)
    paragraphs = []
    for raw in re.split(r"\n+", value):
        paragraph = re.sub(r"[ \t]+", " ", raw).strip(" -—；;,，")
        if not paragraph or compact(paragraph) == compact(title):
            continue
        paragraphs.append(paragraph.replace(",", "，").replace(";", "；"))
    return "\n\n".join(paragraphs)


def markdown_table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    def cell(value: Any) -> str:
        return str(value if value not in (None, "") else "待确认").replace("|", "／").replace("\n", " ")

    lines = [
        "| " + " | ".join(cell(item) for item in headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(cell(item) for item in row) + " |" for row in rows)
    return lines


def scope_groups(scopes: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for scope in scopes:
        name = scope.get("standard_name", "")
        group_name = "other"
        for candidate, keywords in SCOPE_GROUP_RULES:
            if any(keyword.casefold() in name.casefold() for keyword in keywords):
                group_name = candidate
                break
        groups[group_name].append(scope)
    return groups


def scope_context(scopes: list[dict[str, Any]], limit: int = 8) -> str:
    names = [scope["standard_name"] for scope in scopes]
    if not names:
        return "当前尚无可用于正文的客户建设清单"
    shown = "、".join(names[:limit])
    return f"{shown}等{len(names)}项建设内容" if len(names) > limit else shown


def scope_domain(scope: dict[str, Any]) -> str:
    if scope.get("domain") and scope["domain"] not in ("待归类", "其他"):
        return scope["domain"]
    group_name = next(
        (
            candidate
            for candidate, keywords in SCOPE_GROUP_RULES
            if any(keyword.casefold() in scope.get("standard_name", "").casefold() for keyword in keywords)
        ),
        "other",
    )
    return {
        "platform_data": "平台、数据与管理应用",
        "clinical": "临床、护理与医技应用",
        "patient_service": "患者服务",
        "consulting_service": "实施与咨询服务",
        "other": "其他建设内容",
    }[group_name]


def scopes_for_aspect(aspect: str, scopes: list[dict[str, Any]]) -> list[dict[str, Any]]:
    preferences = ASPECT_GROUP_PREFERENCES.get(aspect)
    if not preferences:
        return scopes
    grouped = scope_groups(scopes)
    selected = [scope for group_name in preferences for scope in grouped.get(group_name, [])]
    return selected or scopes


def scope_mode_summary(scopes: list[dict[str, Any]]) -> str:
    modes: dict[str, list[str]] = defaultdict(list)
    for scope in scopes:
        modes[MODE_LABELS.get(scope.get("construction_mode"), "待确认")].append(scope["standard_name"])
    parts = []
    for mode in ("升级", "新建", "利旧", "待确认"):
        if not modes.get(mode):
            continue
        names = "、".join(modes[mode][:5])
        suffix = "等" if len(modes[mode]) > 5 else ""
        parts.append(f"{mode}事项包括{names}{suffix}")
    return "；".join(parts)



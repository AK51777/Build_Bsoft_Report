        (
            f"本节以{project['official_name']}客户建设清单为边界，按照“范围项—业务能力—功能模块—验收要点”组织建设内容。"
            f"{knowledge_statement}"
            "是否纳入本期以及具体配置、接口和数量仍需在需求和设计评审中逐项确认。"
        ),
